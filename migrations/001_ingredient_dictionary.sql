-- Create ingredient dictionary for autocomplete
CREATE TABLE IF NOT EXISTS ingredient_dictionary (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE,
  frequency INT DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Populate from existing products
INSERT IGNORE INTO ingredient_dictionary (name, frequency)
SELECT TRIM(ingredient) as name, COUNT(*) as frequency
FROM (
  SELECT TRIM(SUBSTRING_INDEX(SUBSTRING_INDEX(p.raw_ingredients_text, ',', numbers.n), ',', -1)) AS ingredient
  FROM products p
  CROSS JOIN (
    SELECT 1 n UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5
    UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9 UNION ALL SELECT 10
    UNION ALL SELECT 11 UNION ALL SELECT 12 UNION ALL SELECT 13 UNION ALL SELECT 14 UNION ALL SELECT 15
    UNION ALL SELECT 16 UNION ALL SELECT 17 UNION ALL SELECT 18 UNION ALL SELECT 19 UNION ALL SELECT 20
    UNION ALL SELECT 21 UNION ALL SELECT 22 UNION ALL SELECT 23 UNION ALL SELECT 24 UNION ALL SELECT 25
    UNION ALL SELECT 26 UNION ALL SELECT 27 UNION ALL SELECT 28 UNION ALL SELECT 29 UNION ALL SELECT 30
    UNION ALL SELECT 31 UNION ALL SELECT 32 UNION ALL SELECT 33 UNION ALL SELECT 34 UNION ALL SELECT 35
    UNION ALL SELECT 36 UNION ALL SELECT 37 UNION ALL SELECT 38 UNION ALL SELECT 39 UNION ALL SELECT 40
    UNION ALL SELECT 41 UNION ALL SELECT 42 UNION ALL SELECT 43 UNION ALL SELECT 44 UNION ALL SELECT 45
    UNION ALL SELECT 46 UNION ALL SELECT 47 UNION ALL SELECT 48 UNION ALL SELECT 49 UNION ALL SELECT 50
  ) numbers
  WHERE p.raw_ingredients_text IS NOT NULL
    AND CHAR_LENGTH(p.raw_ingredients_text) - CHAR_LENGTH(REPLACE(p.raw_ingredients_text, ',', '')) >= numbers.n - 1
) parsed
WHERE ingredient IS NOT NULL AND TRIM(ingredient) != ''
GROUP BY TRIM(ingredient)
ORDER BY frequency DESC;
